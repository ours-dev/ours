"""Generate the system-call ABI from //system/public/ours/syscalls.gni.

GN turns the description into JSON (generated_file with
output_conversion = "json"); this reads that and writes whichever outputs it
is asked for. Every check on the description happens on every run, whatever
the outputs, so that a malformed entry is refused by the first build that sees
it rather than by the one output that happens to trip over it.

Standard library only: the host's python3 is 3.9, with no tomllib and nothing
installed beside it. The description is a GN scope list rather than a file in
an interface-definition language of its own, because GN is the one parser this
tree already has.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import re
import sys
from typing import Dict, List, Optional

# The most arguments a call can take: rdi, rsi, rdx, r10, r8, r9, r12, r13
# (design 4.7). A ninth would have to come from the user stack, which the
# kernel would then have to read through user_copy, so the line is drawn at
# eight: every argument arrives in a register.
MAX_ARGS = 8

KNOWN_ATTRS = {"blocking", "noreturn", "debug", "vdso"}
KNOWN_DIRS = {"in", "out"}
KNOWN_ARG_KEYS = {"name", "type", "dir", "count", "release"}
KNOWN_CALL_KEYS = {"name", "brief", "doc", "args", "attrs", "ret", "category"}

# Types that are spelled without a namespace. Everything else is a type in
# namespace ours.
PRIMITIVES = {
    "void", "char",
    "u8", "u16", "u32", "u64", "usize",
    "i8", "i16", "i32", "i64", "isize",
}

# The tree's .clang-format column limit; generated code is read as well.
LINE_WIDTH = 100

IDENTIFIER = re.compile(r"^[a-z][a-z0-9_]*$")
TYPE_NAME = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")

HEADER_BANNER = (
    "// Generated by //build/abi/gen_syscalls.py from\n"
    "// //system/public/ours/syscalls/*.gni. Do not edit.\n"
)


class DescriptionError(Exception):
    pass


class Arg:
    def __init__(self, raw: Dict, call: str, position: int) -> None:
        where = f"{call}, argument {position}"
        unknown = set(raw) - KNOWN_ARG_KEYS
        if unknown:
            raise DescriptionError(f"{where}: unknown keys {sorted(unknown)}")
        for key in ("name", "type"):
            if key not in raw:
                raise DescriptionError(f"{where}: no {key}")

        self.name: str = raw["name"]
        self.type: str = raw["type"]
        self.dir: Optional[str] = raw.get("dir")
        self.count: Optional[str] = raw.get("count")
        self.release: bool = bool(raw.get("release", False))

        if not IDENTIFIER.match(self.name):
            raise DescriptionError(f"{where}: '{self.name}' is not a lower_snake_case name")
        if not TYPE_NAME.match(self.type):
            raise DescriptionError(f"{where}: '{self.type}' is not a type name")
        if self.dir is not None and self.dir not in KNOWN_DIRS:
            raise DescriptionError(f"{where}: dir must be one of {sorted(KNOWN_DIRS)}")
        if self.dir is None and self.count is not None:
            raise DescriptionError(f"{where}: count on an argument that is not a pointer")
        if self.dir is None and self.type == "void":
            raise DescriptionError(f"{where}: void is only a pointee")
        # A handle a call consumes is an ours::Uandle the caller hands in:
        # one passed by value, or an input array of them (channel_write's
        # handles). Never an output -- a handle the kernel writes out is one
        # the caller receives, not one it gives up.
        if self.release and (self.type != "Uandle" or self.dir not in (None, "in")):
            raise DescriptionError(
                f"{where}: release is only for a Uandle passed by value or as an input array")

    @property
    def is_pointer(self) -> bool:
        return self.dir is not None


class Call:
    def __init__(self, raw: Dict, number: int) -> None:
        unknown = set(raw) - KNOWN_CALL_KEYS
        if unknown:
            raise DescriptionError(f"entry {number}: unknown keys {sorted(unknown)}")
        if "name" not in raw:
            raise DescriptionError(f"entry {number}: no name")

        self.name: str = raw["name"]
        self.number = number
        # The file the call is described in (ours/syscalls/<category>.gni),
        # which is also the kernel file that defines the handler and, from
        # the generator's per-category outputs, the declaration header the
        # call lands in.
        self.category: str = raw.get("category", "")
        if not IDENTIFIER.match(self.category):
            raise DescriptionError(f"{self.name}: no category")
        self.brief: str = raw.get("brief", "")
        self.doc: List[str] = list(raw.get("doc", []))
        self.attrs: List[str] = list(raw.get("attrs", []))
        self.ret: str = raw.get("ret", "Status")

        if not IDENTIFIER.match(self.name):
            raise DescriptionError(f"entry {number}: '{self.name}' is not a lower_snake_case name")
        if not self.brief:
            raise DescriptionError(f"{self.name}: no brief")
        unknown_attrs = set(self.attrs) - KNOWN_ATTRS
        if unknown_attrs:
            raise DescriptionError(f"{self.name}: unknown attrs {sorted(unknown_attrs)}")
        if not TYPE_NAME.match(self.ret):
            raise DescriptionError(f"{self.name}: '{self.ret}' is not a type name")
        # A call that returns nothing is one that never returns: the result
        # register is the only way back, and a call that comes back without
        # using it has told the caller nothing it can check.
        if ("noreturn" in self.attrs) != (self.ret == "void"):
            raise DescriptionError(f"{self.name}: ret is void exactly when the call is noreturn")
        # The stub of a blocking call compares the result with InternalIrqRetry
        # and traps again on it, which means something only for a Status --
        # and a noreturn call has no result at all.
        if "blocking" in self.attrs and self.ret != "Status":
            raise DescriptionError(f"{self.name}: a blocking call returns Status")

        raw_args = raw.get("args", [])
        if len(raw_args) > MAX_ARGS:
            raise DescriptionError(f"{self.name}: {len(raw_args)} arguments, at most {MAX_ARGS}")
        self.args = [Arg(a, self.name, i) for i, a in enumerate(raw_args)]

        names = [a.name for a in self.args]
        duplicated = {n for n in names if names.count(n) > 1}
        if duplicated:
            raise DescriptionError(f"{self.name}: repeated argument names {sorted(duplicated)}")
        for arg in self.args:
            if arg.count is None:
                continue
            # A count must name a scalar the caller passes by value: a length
            # the kernel reads through a pointer could change between the
            # read and the copy it bounds.
            target = next((a for a in self.args if a.name == arg.count), None)
            if target is None:
                raise DescriptionError(
                    f"{self.name}: '{arg.name}' is counted by '{arg.count}', which is not an argument")
            if target.is_pointer:
                raise DescriptionError(
                    f"{self.name}: '{arg.name}' is counted by '{arg.count}', which is a pointer")

    @property
    def upper(self) -> str:
        return self.name.upper()

    @property
    def noreturn(self) -> bool:
        return "noreturn" in self.attrs


def load(path: pathlib.Path) -> List[Call]:
    raw = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(raw, list) or not raw:
        raise DescriptionError("the description is not a non-empty list")
    calls = [Call(entry, number) for number, entry in enumerate(raw)]
    names = [c.name for c in calls]
    duplicated = {n for n in names if names.count(n) > 1}
    if duplicated:
        raise DescriptionError(f"repeated call names {sorted(duplicated)}")
    return calls


def write_if_changed(path: pathlib.Path, text: str) -> None:
    """Leaves an unchanged output untouched, so that GN's restat can stop
    the rebuild of everything that includes it."""
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def render_numbers(calls: List[Call]) -> str:
    lines = [
        HEADER_BANNER,
        "#ifndef SYSCALL_ABI_NUMBERS_HPP",
        "#define SYSCALL_ABI_NUMBERS_HPP 1",
        "",
        "#include <ours/types.hpp>",
        "",
        "#include <string_view>",
        "",
        "/// The system-call numbers: a private agreement between the kernel's",
        "/// dispatch table and the vDSO's stubs (design D8). A program names a",
        "/// call by its vDSO symbol and never sees one of these.",
        "namespace ours::syscall_abi {",
        "/// Numbers are dense from zero, so this is one past the largest.",
        f"inline constexpr auto SYSCALL_COUNT = usize{{{len(calls)}}};",
        "",
    ]
    for call in calls:
        lines.append(f"inline constexpr auto SYS_{call.upper} = usize{{{call.number}}};")
    lines += [
        "",
        "/// For diagnostics: the name of call |n| is SYSCALL_NAMES[n].",
        "inline constexpr std::string_view SYSCALL_NAMES[SYSCALL_COUNT] = {",
    ]
    for call in calls:
        lines.append(f'    "{call.name}",')
    lines += [
        "};",
        "} // namespace ours::syscall_abi",
        "",
        "#endif // SYSCALL_ABI_NUMBERS_HPP",
        "",
    ]
    return "\n".join(lines)


def render_vdso_stubs(calls: List[Call]) -> str:
    """One `ours_syscall` line per call, for the macro in the vDSO's vdso.S.

    The macro is written by hand and this only instantiates it: the shape of
    a stub is assembly worth reading once, and the list of stubs is the part
    that has to follow the description.
    """
    # `//` comments are fine: vdso.S goes through the C preprocessor, which
    # strips them before the assembler sees the line.
    lines = [HEADER_BANNER]
    for call in calls:
        noreturn = 1 if "noreturn" in call.attrs else 0
        blocking = 1 if "blocking" in call.attrs else 0
        # A call whose body the vDSO supplies keeps the trap under a hidden
        # name, so the public symbol can be the body and the body can fall
        # back to the trap.
        name = f"ours_{call.name}_via_kernel" if "vdso" in call.attrs else f"ours_{call.name}"
        lines.append(
            f"ours_syscall {name}, OURS_VDSO_SYSRET_{call.upper}, "
            f"{call.number}, {len(call.args)}, {noreturn}, {blocking}")
        if "vdso" in call.attrs:
            lines.append(f".hidden {name}")
    lines.append("")
    return "\n".join(lines)


def kernel_type(arg: Arg) -> str:
    """The type a handler takes |arg| as: primitives bare, every other type
    fully qualified as ours::<name> (user_type()).

    Qualified so that a declaration means the same thing in every file that
    includes it. A file in ours::syscall may carry `using object::Handle;`,
    and there a bare `Handle` is the kernel's object::Handle class, a
    different type from the value ours::Uandle.

    A pointer is a user_copy::UserPtr and never a C++ pointer: the kernel can
    copy through it but cannot dereference it, and its direction is part of
    the type, so writing through an input does not compile. `void` data is
    carried as bytes.
    """
    # user_type() is defined further down; Python looks the name up when this
    # runs, not when it is defined.
    base = user_type(arg.type)
    if not arg.is_pointer:
        return base
    pointee = "u8" if arg.type == "void" else base
    if arg.dir == "in":
        return f"user_copy::UserInPtr<{pointee} const>"
    return f"user_copy::UserOutPtr<{pointee}>"


def render_kernel_decls(calls: List[Call]) -> str:
    """The typed handler declarations, included by <syscall/handlers.hpp>
    inside namespace ours::syscall: syscall::<name>, with no sys_ prefix --
    the namespace already says what it is.

    Each handler is defined by hand, so a definition that has drifted from
    its entry here is a different overload that nothing calls, and the
    generated shim's call to this one fails to link.
    """
    lines = [HEADER_BANNER]
    for call in calls:
        params = [f"{kernel_type(a)} {a.name}" for a in call.args]
        lines.append(f"/// {call.brief}")
        if call.noreturn:
            lines.append("[[noreturn]]")
        one_line = f"auto {call.name}({', '.join(params)}) -> {call.ret};"
        if len(one_line) <= LINE_WIDTH:
            lines.append(one_line)
        else:
            joined = ",\n    ".join(params)
            lines.append(f"auto {call.name}(\n    {joined}) -> {call.ret};")
        lines.append("")
    return "\n".join(lines)


def render_kernel_shims(calls: List[Call]) -> str:
    """One shim per call, which unpacks arch::SyscallFrame into the handler's
    arguments and puts the result back in the frame, and the table of them.

    Included by table.cpp inside its anonymous namespace, after the
    SyscallHandler type. The result goes into `frame->ax` rather than being
    returned because the entry stub pops the whole frame back into the
    registers on its way out, so a C++ return value would be overwritten.
    """
    lines = [HEADER_BANNER]
    for call in calls:
        lines.append(f"auto {call.name}_shim(arch::SyscallFrame *const frame) -> void {{")
        arguments = [
            f"syscall::from_register<{kernel_type(a)}>(arch::syscall_arg<{i}>(frame))"
            for i, a in enumerate(call.args)
        ]
        if not arguments:
            invocation = f"syscall::{call.name}()"
        else:
            joined = ",\n        ".join(arguments)
            invocation = f"syscall::{call.name}(\n        {joined})"
        if call.noreturn:
            lines.append(f"    {invocation};")
        else:
            lines.append(f"    auto const result = {invocation};")
            lines.append("    frame->ax = static_cast<usize>(result);")
        lines.append("}")
        lines.append("")
    lines.append("constexpr SyscallHandler GENERATED_SHIMS[] = {")
    for call in calls:
        lines.append(f"    &{call.name}_shim,")
    lines.append("};")
    lines.append("static_assert(std::size(GENERATED_SHIMS) == syscall_abi::SYSCALL_COUNT);")
    lines.append("")
    return "\n".join(lines)


def user_type(name: str) -> str:
    """|name| as a program spells it: primitives bare, the rest in ours::."""
    return name if name in PRIMITIVES else f"ours::{name}"


def user_param(arg: Arg) -> str:
    if not arg.is_pointer:
        return f"{user_type(arg.type)} {arg.name}"
    const = " const" if arg.dir == "in" else ""
    return f"{user_type(arg.type)}{const} *{arg.name}"


def render_vdso_decls(calls: List[Call]) -> str:
    """One category's vDSO entries as a program calls them, included by that
    category's public header (and by <ours/vdso.hpp>, through all.inc) inside
    namespace ours: `ours::<name>`, with an asm label that names the vDSO's
    symbol, `ours_<name>`, so that the call binds to that symbol and not to a
    mangled C++ name (see <ours/vdso.hpp>).

    The documentation is the description's, written for the caller, and this
    is the one place a program reads it: there is no wrapper library that
    restates it.
    """
    lines = [HEADER_BANNER]
    for call in calls:
        lines.append(f"/// {call.brief}")
        if call.doc:
            lines.append("///")
            lines += [f"/// {line}".rstrip() for line in call.doc]
        if call.noreturn:
            lines.append("[[noreturn]]")
        params = [user_param(a) for a in call.args]
        ret = user_type(call.ret)
        label = f'__asm__("ours_{call.name}")'
        one_line = f"auto {call.name}({', '.join(params)}) -> {ret} {label};"
        if len(one_line) <= LINE_WIDTH:
            lines.append(one_line)
        else:
            joined = ",\n    ".join(params)
            lines.append(f"auto {call.name}(\n    {joined}) -> {ret} {label};")
        lines.append("")
    return "\n".join(lines)


def render_vdso_decls_all(calls: List[Call]) -> str:
    """The umbrella include <ours/vdso_decls/all.inc>: one include per
    category, in the number order ours/syscalls.gni's concatenation spells.
    <ours/vdso.hpp> includes this file; a domain's own header includes its
    category's file directly.
    """
    categories = []
    for call in calls:
        if call.category not in categories:
            categories.append(call.category)
    lines = [HEADER_BANNER]
    lines.append("// One file per category; the order here is the call-number order.")
    for cat in categories:
        lines.append(f"#include <ours/vdso_decls/{cat}.inc>")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("description", type=pathlib.Path,
                        help="the description as JSON, from generated_file()")
    parser.add_argument("--numbers", type=pathlib.Path,
                        help="write the private call-number header here")
    parser.add_argument("--vdso-stubs", type=pathlib.Path,
                        help="write the vDSO's stub instantiations here")
    parser.add_argument("--kernel-decls", type=pathlib.Path,
                        help="write the kernel's handler declarations here")
    parser.add_argument("--kernel-shims", type=pathlib.Path,
                        help="write the kernel's frame-unpacking shims here")
    parser.add_argument("--vdso-decls-dir", type=pathlib.Path,
                        help="write the per-category declarations of the vDSO's"
                             " entries under here, as vdso_decls/<category>.inc"
                             " plus the all.inc umbrella")
    args = parser.parse_args()

    try:
        calls = load(args.description)
    except DescriptionError as error:
        print(f"{args.description}: {error}", file=sys.stderr)
        return 1

    if args.numbers:
        write_if_changed(args.numbers, render_numbers(calls))
    if args.vdso_stubs:
        write_if_changed(args.vdso_stubs, render_vdso_stubs(calls))
    if args.kernel_decls:
        write_if_changed(args.kernel_decls, render_kernel_decls(calls))
    if args.kernel_shims:
        write_if_changed(args.kernel_shims, render_kernel_shims(calls))
    if args.vdso_decls_dir:
        args.vdso_decls_dir.mkdir(parents=True, exist_ok=True)
        categories = []
        for call in calls:
            if call.category not in categories:
                categories.append(call.category)
        for cat in categories:
            write_if_changed(
                args.vdso_decls_dir / "vdso_decls" / f"{cat}.inc",
                render_vdso_decls([c for c in calls if c.category == cat]))
        write_if_changed(
            args.vdso_decls_dir / "vdso_decls" / "all.inc",
            render_vdso_decls_all(calls))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
