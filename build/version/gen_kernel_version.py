"""Write the kernel version string, including the short commit it was built from.

argv: repo_root base_version output depfile

The string is base_version, '+', then 12 hex digits of HEAD. A dirty work
tree appends '-dirty': the hash is then the commit the tree started from,
not a commit that contains these sources. If git cannot name HEAD, the
suffix is 'unknown'.
"""

import subprocess
import sys
from pathlib import Path


def _git(root: str, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(
        ["git", "-C", root, *args],
        check=False,
        capture_output=True,
        text=True,
    )


def main() -> None:
    if len(sys.argv) != 5:
        print(
            "usage: gen_kernel_version.py repo_root base_version output depfile",
            file=sys.stderr,
        )
        sys.exit(1)
    root, base, output, depfile = sys.argv[1:]
    revision = _git(root, "rev-parse", "--short=12", "HEAD")
    if revision.returncode != 0 or not revision.stdout.strip():
        suffix = "unknown"
        inputs = []
    else:
        suffix = revision.stdout.strip()
        status = _git(root, "status", "--porcelain")
        if status.returncode == 0 and status.stdout.strip():
            suffix += "-dirty"
        inputs = []
        for name in ("HEAD", "index"):
            located = _git(root, "rev-parse", "--git-path", name)
            if located.returncode == 0 and located.stdout.strip():
                path = Path(located.stdout.strip())
                if not path.is_absolute():
                    path = Path(root) / path
                inputs.append(path.resolve())

    text = f"{base}+{suffix}"
    header = (
        "// Generated by //build/version/gen_kernel_version.py. Do not edit.\n"
        f'#define OURS_KERNEL_VERSION_STRING "{text}"\n'
    )
    out = Path(output)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(header, encoding="utf-8")
    dep = Path(depfile)
    listed = " ".join(str(path) for path in inputs)
    dep.write_text(f"{output}: {listed}\n", encoding="utf-8")


if __name__ == "__main__":
    main()
