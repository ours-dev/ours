"""Generate the system-call ABI from //system/public/ours/syscalls.gni.

GN turns the description into JSON (generated_file with
output_conversion = "json"); this reads that and writes whichever outputs it
is asked for. Every check on the description happens on every run, whatever
the outputs, so that a malformed entry is refused by the first build that sees
it rather than by the one output that happens to trip over it.

Standard library only: the host's python3 is 3.9, with no tomllib and nothing
installed beside it. Zircon's counterpart is kazoo, which reads FIDL; the
description here is a GN scope list because GN is the one parser this tree
already has.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import re
import sys
from typing import Dict, List, Optional

# The most arguments a call can take: rdi, rsi, rdx, r10, r8, r9, r12, r13
# (design 4.7). A ninth would have to come from the user stack, which the
# kernel would then have to read through user_copy -- Zircon draws the line at
# eight for the same reason.
MAX_ARGS = 8

# A seventh argument needs a stub that saves and loads only %r12. It is left
# out until a call needs one (vmar_map, design P1-C), rather than written now
# with nothing to exercise it.
UNSUPPORTED_ARG_COUNTS = {7}

KNOWN_ATTRS = {"blocking", "noreturn", "debug"}
KNOWN_DIRS = {"in", "out"}
KNOWN_ARG_KEYS = {"name", "type", "dir", "count", "release"}
KNOWN_CALL_KEYS = {"name", "brief", "doc", "args", "attrs", "ret"}

# Types that are spelled without a namespace. Everything else is a type in
# namespace ours.
PRIMITIVES = {
    "void", "char",
    "u8", "u16", "u32", "u64", "usize",
    "i8", "i16", "i32", "i64", "isize",
}

IDENTIFIER = re.compile(r"^[a-z][a-z0-9_]*$")
TYPE_NAME = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")

HEADER_BANNER = (
    "// Generated by //build/syscall/gen_syscalls.py from\n"
    "// //system/public/ours/syscalls.gni. Do not edit.\n"
)


class DescriptionError(Exception):
    pass


class Arg:
    def __init__(self, raw: Dict, call: str, position: int) -> None:
        where = f"{call}, argument {position}"
        unknown = set(raw) - KNOWN_ARG_KEYS
        if unknown:
            raise DescriptionError(f"{where}: unknown keys {sorted(unknown)}")
        for key in ("name", "type"):
            if key not in raw:
                raise DescriptionError(f"{where}: no {key}")

        self.name: str = raw["name"]
        self.type: str = raw["type"]
        self.dir: Optional[str] = raw.get("dir")
        self.count: Optional[str] = raw.get("count")
        self.release: bool = bool(raw.get("release", False))

        if not IDENTIFIER.match(self.name):
            raise DescriptionError(f"{where}: '{self.name}' is not a lower_snake_case name")
        if not TYPE_NAME.match(self.type):
            raise DescriptionError(f"{where}: '{self.type}' is not a type name")
        if self.dir is not None and self.dir not in KNOWN_DIRS:
            raise DescriptionError(f"{where}: dir must be one of {sorted(KNOWN_DIRS)}")
        if self.dir is None and self.count is not None:
            raise DescriptionError(f"{where}: count on an argument that is not a pointer")
        if self.dir is None and self.type == "void":
            raise DescriptionError(f"{where}: void is only a pointee")
        # A handle a call consumes is a handle *value*: a pointer to handles
        # would need the kernel to say which of them it took.
        if self.release and (self.type != "HandleValue" or self.dir is not None):
            raise DescriptionError(f"{where}: release is only for a HandleValue passed by value")

    @property
    def is_pointer(self) -> bool:
        return self.dir is not None


class Call:
    def __init__(self, raw: Dict, number: int) -> None:
        unknown = set(raw) - KNOWN_CALL_KEYS
        if unknown:
            raise DescriptionError(f"entry {number}: unknown keys {sorted(unknown)}")
        if "name" not in raw:
            raise DescriptionError(f"entry {number}: no name")

        self.name: str = raw["name"]
        self.number = number
        self.brief: str = raw.get("brief", "")
        self.doc: List[str] = list(raw.get("doc", []))
        self.attrs: List[str] = list(raw.get("attrs", []))
        self.ret: str = raw.get("ret", "Status")

        if not IDENTIFIER.match(self.name):
            raise DescriptionError(f"entry {number}: '{self.name}' is not a lower_snake_case name")
        if not self.brief:
            raise DescriptionError(f"{self.name}: no brief")
        unknown_attrs = set(self.attrs) - KNOWN_ATTRS
        if unknown_attrs:
            raise DescriptionError(f"{self.name}: unknown attrs {sorted(unknown_attrs)}")
        if not TYPE_NAME.match(self.ret):
            raise DescriptionError(f"{self.name}: '{self.ret}' is not a type name")

        raw_args = raw.get("args", [])
        if len(raw_args) > MAX_ARGS:
            raise DescriptionError(f"{self.name}: {len(raw_args)} arguments, at most {MAX_ARGS}")
        if len(raw_args) in UNSUPPORTED_ARG_COUNTS:
            raise DescriptionError(
                f"{self.name}: {len(raw_args)} arguments has no vDSO stub shape yet")
        self.args = [Arg(a, self.name, i) for i, a in enumerate(raw_args)]

        names = [a.name for a in self.args]
        duplicated = {n for n in names if names.count(n) > 1}
        if duplicated:
            raise DescriptionError(f"{self.name}: repeated argument names {sorted(duplicated)}")
        for arg in self.args:
            if arg.count is None:
                continue
            # A count must name a scalar the caller passes by value: a length
            # the kernel reads through a pointer could change between the
            # read and the copy it bounds.
            target = next((a for a in self.args if a.name == arg.count), None)
            if target is None:
                raise DescriptionError(
                    f"{self.name}: '{arg.name}' is counted by '{arg.count}', which is not an argument")
            if target.is_pointer:
                raise DescriptionError(
                    f"{self.name}: '{arg.name}' is counted by '{arg.count}', which is a pointer")

    @property
    def upper(self) -> str:
        return self.name.upper()


def load(path: pathlib.Path) -> List[Call]:
    raw = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(raw, list) or not raw:
        raise DescriptionError("the description is not a non-empty list")
    calls = [Call(entry, number) for number, entry in enumerate(raw)]
    names = [c.name for c in calls]
    duplicated = {n for n in names if names.count(n) > 1}
    if duplicated:
        raise DescriptionError(f"repeated call names {sorted(duplicated)}")
    return calls


def write_if_changed(path: pathlib.Path, text: str) -> None:
    """Leaves an unchanged output untouched, so that GN's restat can stop
    the rebuild of everything that includes it."""
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def render_numbers(calls: List[Call]) -> str:
    lines = [
        HEADER_BANNER,
        "#ifndef SYSCALL_ABI_NUMBERS_HPP",
        "#define SYSCALL_ABI_NUMBERS_HPP 1",
        "",
        "#include <ours/types.hpp>",
        "",
        "#include <string_view>",
        "",
        "/// The system-call numbers: a private agreement between the kernel's",
        "/// dispatch table and the vDSO's stubs (design D8). A program names a",
        "/// call by its vDSO symbol and never sees one of these.",
        "namespace ours::syscall_abi {",
        "/// Numbers are dense from zero, so this is one past the largest.",
        f"inline constexpr auto SYSCALL_COUNT = usize{{{len(calls)}}};",
        "",
    ]
    for call in calls:
        lines.append(f"inline constexpr auto SYS_{call.upper} = usize{{{call.number}}};")
    lines += [
        "",
        "/// For diagnostics: the name of call |n| is SYSCALL_NAMES[n].",
        "inline constexpr std::string_view SYSCALL_NAMES[SYSCALL_COUNT] = {",
    ]
    for call in calls:
        lines.append(f'    "{call.name}",')
    lines += [
        "};",
        "} // namespace ours::syscall_abi",
        "",
        "#endif // SYSCALL_ABI_NUMBERS_HPP",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("description", type=pathlib.Path,
                        help="the description as JSON, from generated_file()")
    parser.add_argument("--numbers", type=pathlib.Path,
                        help="write the private call-number header here")
    args = parser.parse_args()

    try:
        calls = load(args.description)
    except DescriptionError as error:
        print(f"{args.description}: {error}", file=sys.stderr)
        return 1

    if args.numbers:
        write_if_changed(args.numbers, render_numbers(calls))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
