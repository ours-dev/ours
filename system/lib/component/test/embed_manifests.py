"""Write compiled manifests into a C++ header as byte arrays.

The decoder's test reads the manifests component_manifest() built from the
targets in fixtures/; carrying them in the binary lets the test run from any
directory. Clang 23 still takes #embed in C++ only as an extension
(-Wc23-extensions), which -Werror refuses, hence a header.

Standard library only: the host's python3 is 3.9, with nothing installed
beside it.
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys

IDENTIFIER = re.compile(r"[A-Z_][A-Z0-9_]*")


def render(entries: list[tuple[str, str, bytes]]) -> str:
    lines = [
        "// Generated by //system/lib/component/test/embed_manifests.py. Do not edit.\n",
        "#ifndef COMPONENT_TEST_FIXTURES_MANIFESTS_HPP\n",
        "#define COMPONENT_TEST_FIXTURES_MANIFESTS_HPP 1\n",
        "\n",
        "#include <array>\n",
        "\n",
        "namespace fixtures {\n",
    ]
    for name, path, data in entries:
        lines.append(f"/// {path}\n")
        lines.append(f"inline constexpr std::array<u8, {len(data)}> {name}{{\n")
        for start in range(0, len(data), 12):
            row = ", ".join(f"0x{byte:02x}" for byte in data[start : start + 12])
            lines.append(f"    {row},\n")
        lines.append("};\n")
    lines.append("} // namespace fixtures\n")
    lines.append("\n#endif // #ifndef COMPONENT_TEST_FIXTURES_MANIFESTS_HPP\n")
    return "".join(lines)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--output", required=True)
    parser.add_argument("manifests", nargs="+", metavar="NAME=PATH")
    args = parser.parse_args(argv)

    entries = []
    for manifest in args.manifests:
        name, _, path = manifest.partition("=")
        if not IDENTIFIER.fullmatch(name) or not path:
            sys.exit(f"embed_manifests: '{manifest}' is not NAME=PATH")
        entries.append((name, path, pathlib.Path(path).read_bytes()))

    output = pathlib.Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(render(entries))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
