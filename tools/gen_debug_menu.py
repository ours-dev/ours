#!/usr/bin/env python3
"""Regenerate the debug menu in ours.code-workspace from the source tree.

VS Code cannot compute a pickString's options -- there is no hook for it short
of a third-party extension -- so the three dropdowns F5 puts up have to be
literal lists in the workspace file.  This writes those lists instead of a
person writing them, so that adding a product, an architecture or a switchset
shows up in the menu without anyone remembering to go and edit it.

All three lists come from the tree, not from a build directory:

    products      products/*.gni                    (tools/set.py's own list)
    arches        tools/set.py's VALID_CPUS
    switchsets    build/switch/set/*/BUILD.gn that instantiate kernel_switchset

The last one is filtered rather than globbed: //build/switch/set also holds the
phys switchsets (phys.dbg_0), and a kernel image's kernel is never built in
one.  The test is which template the directory instantiates, which is the same
thing GN uses.

Deliberately NOT consulted: any out/ directory.  The menu is a list of things
that can be asked for, and a build directory only knows about the one product
and architecture it was configured for -- generating from it would shrink the
menu to whatever happened to be configured last.  Whether a particular
combination actually exists is scripts/qemu_debug.py's job, and it answers with
the real alternatives when one does not.

Idempotent: it only writes when the result differs, so running it from
tools/set.py on every `gn gen` costs nothing and leaves no git churn.

    tools/gen_debug_menu.py             # rewrite if needed
    tools/gen_debug_menu.py --check     # exit 1 if it would rewrite
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import set as set_py  # noqa: E402  (tools/set.py -- the arch table lives there)

ROOT = Path(__file__).resolve().parent.parent
WORKSPACE = ROOT / "ours.code-workspace"

BEGIN = "// BEGIN generated by tools/gen_debug_menu.py -- do not edit by hand"
END = "// END generated by tools/gen_debug_menu.py"

# What each value means, for the rows that have something worth saying.  A
# missing entry is not an error: the value shows on its own, which is the right
# outcome for a name nobody has described yet -- better than blocking the
# generator on a table it cannot derive.
#
# VS Code renders an option as "<label>: <value>", so a label must not repeat
# the value it labels.
DESCRIPTIONS = {
    "product": {
        "bringup": "minimal bootable image set",
    },
    "arch": {
        "x86": "the one that boots today",
        "arm": "aarch64",
        "riscv": "riscv64",
    },
    "switchset": {
        "dbg.0": "asserts compiled out, unit tests linked in",
        "dbg.1": "asserts and trace on",
        "dbg.2": "more tracing again",
    },
}

DEFAULTS = {"product": "bringup", "arch": "x86", "switchset": "dbg.1"}

PROMPTS = {
    "product": "Product?",
    "arch": "Architecture?",
    "switchset": "Which kernel?",
}


def kernel_switchsets() -> list[str]:
    """Switchset names that build a kernel, not the phys environment."""
    root = ROOT / "build" / "switch" / "set"
    if not root.is_dir():
        return []
    found = []
    for build_gn in sorted(root.glob("*/BUILD.gn")):
        if re.search(r"^\s*kernel_switchset\(", build_gn.read_text(), re.M):
            found.append(build_gn.parent.name)
    return found


def render(products: list[str], arches: list[str], switchsets: list[str]) -> str:
    """The JSONC for the three inputs, indented to sit inside "tasks"."""
    pad = " " * 8

    def option(kind: str, value: str) -> list[str]:
        label = DESCRIPTIONS.get(kind, {}).get(value)
        body = [f'{pad}            {{']
        if label:
            body.append(f'{pad}                "label": {json.dumps(label)},')
        body.append(f'{pad}                "value": {json.dumps(value)}')
        body.append(f'{pad}            }}')
        return body

    def block(kind: str, values: list[str]) -> list[str]:
        default = DEFAULTS[kind]
        # A default that is no longer in the tree would leave the row unmarked
        # and preselect nothing; fall back rather than emit a dangling name.
        if default not in values:
            default = values[0] if values else ""
        out = [
            f'{pad}    {{',
            f'{pad}        "id": {json.dumps(kind)},',
            f'{pad}        "type": "pickString",',
            f'{pad}        "description": {json.dumps(PROMPTS[kind])},',
            f'{pad}        "default": {json.dumps(default)},',
            f'{pad}        "options": [',
        ]
        for n, value in enumerate(values):
            rows = option(kind, value)
            if n != len(values) - 1:
                rows[-1] += ","
            out += rows
        out += [f'{pad}        ]', f'{pad}    }}']
        return out

    lines = [f'{pad}"inputs": [']
    kinds = [("product", products), ("arch", arches), ("switchset", switchsets)]
    for n, (kind, values) in enumerate(kinds):
        rows = block(kind, values)
        if n != len(kinds) - 1:
            rows[-1] += ","
        lines += rows
    lines.append(f"{pad}]")
    return "\n".join(lines)


def splice(text: str, generated: str) -> str:
    pad = " " * 8
    pattern = re.compile(
        r"(^[ \t]*" + re.escape(BEGIN) + r"[ \t]*$)(.*?)(^[ \t]*" + re.escape(END) + r"[ \t]*$)",
        re.S | re.M,
    )
    if not pattern.search(text):
        raise SystemExit(
            f"{WORKSPACE}: no generated region found.\n"
            f"Add these two lines around the \"inputs\" array:\n"
            f"  {pad}{BEGIN}\n  ...\n  {pad}{END}"
        )
    return pattern.sub(lambda m: f"{m.group(1)}\n{generated}\n{pad}{END}", text)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="exit 1 if the file would change, and write nothing")
    parser.add_argument("--quiet", action="store_true",
                        help="say nothing when there is nothing to do")
    args = parser.parse_args(argv)

    products = set_py.list_products()
    arches = list(set_py.VALID_CPUS)
    switchsets = kernel_switchsets()

    for name, values in (("product", products), ("arch", arches),
                         ("switchset", switchsets)):
        if not values:
            print(f"gen_debug_menu: found no {name}s -- refusing to write an "
                  f"empty menu", file=sys.stderr)
            return 1

    before = WORKSPACE.read_text()
    after = splice(before, render(products, arches, switchsets))

    if after == before:
        if not args.quiet:
            print(f"gen_debug_menu: {WORKSPACE.name} is up to date "
                  f"({len(products)} products, {len(arches)} arches, "
                  f"{len(switchsets)} switchsets)")
        return 0

    if args.check:
        print(f"gen_debug_menu: {WORKSPACE.name} is stale -- "
              f"run tools/gen_debug_menu.py", file=sys.stderr)
        return 1

    WORKSPACE.write_text(after)
    print(f"gen_debug_menu: rewrote {WORKSPACE.name} "
          f"(products: {' '.join(products)}; arches: {' '.join(arches)}; "
          f"switchsets: {' '.join(switchsets)})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
