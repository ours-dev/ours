"""Generate code-patches.inc from hermetic alternative metadata.

Reads a JSON file containing entries of the form:
  { "name": "swapgs_stub", "case_id": "SWAPGS_BUG", "path": "/.../blob.bin" }

Groups by case_id, computes the maximum blob file size per case, assigns
deterministic numeric IDs (sorted case_id order → 1, 2, …), and emits:

  .set CODE_PATCH_MAX_SWAPGS_BUG, 32
  .set CASE_ID_SWAPGS_BUG,       1

This is the ONLY file assembly sources need to include.
"""

import argparse
import json
import os
import sys
from collections import defaultdict


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--metadata-file", required=True,
                        help="JSON file with alternative metadata entries")
    parser.add_argument("--depfile", required=True,
                        help="Ninja depfile to write")
    parser.add_argument("--outfile", required=True,
                        help="Output .inc file path")
    args = parser.parse_args()

    with open(args.metadata_file, encoding="utf-8") as f:
        entries = json.load(f)

    if not entries:
        with open(args.outfile, "w", encoding="utf-8") as f:
            f.write("// No hermetic alternatives found.\n")
        with open(args.depfile, "w", encoding="utf-8") as f:
            f.write(f"{args.outfile}: {args.metadata_file}\n")
        return 0

    # Group by case_id, compute max blob size per case.
    case_max_size: dict[str, int] = defaultdict(int)
    deps: list[str] = [args.metadata_file]

    for entry in entries:
        path = entry["path"]
        deps.append(path)
        case_id = entry["case_id"]
        blob_size = os.path.getsize(path)
        if blob_size > case_max_size[case_id]:
            case_max_size[case_id] = blob_size

    # Auto-assign deterministic numeric IDs (sorted → 1, 2, 3, …).
    sorted_cases = sorted(case_max_size.keys())
    case_id_num = {case_id: idx for idx, case_id in enumerate(sorted_cases, start=1)}

    # Emit both max size and numeric ID per case.
    with open(args.outfile, "w", encoding="utf-8") as f:
        f.write("// Auto-generated by generate-case-sizes.py. Do not edit.\n")
        f.write("//\n")
        f.write("// One CODE_PATCH_MAX_<case> / CASE_ID_<case> pair per case.\n")
        f.write("// Included by assembly sources that use .code_patch_end /\n")
        f.write("// .code_patching.blob.\n\n")
        for case_id in sorted_cases:
            size = case_max_size[case_id]
            num  = case_id_num[case_id]
            f.write(f".set CODE_PATCH_MAX_{case_id}, {size}\n")
            f.write(f".set CASE_ID_{case_id},       {num}\n")

    with open(args.depfile, "w", encoding="utf-8") as f:
        f.write(f"{args.outfile}: {' '.join(deps)}\n")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
