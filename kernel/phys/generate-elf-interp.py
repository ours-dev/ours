"""Generate assembly containing one dependency ELF's GNU build ID."""

import argparse
import json
import pathlib
import re


BUILD_ID = re.compile(r"[0-9a-f]+")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("metadata", help="JSON containing elf_build_ids metadata")
    parser.add_argument("output", help="assembly include to generate")
    parser.add_argument("depfile", help="Ninja depfile to generate")
    args = parser.parse_args()

    metadata_path = pathlib.Path(args.metadata)
    entries = json.loads(metadata_path.read_text(encoding="utf-8"))
    if len(entries) != 1:
        parser.error(f"expected exactly one ELF build ID, found {len(entries)}")

    build_id_path = pathlib.Path(entries[0]["build_id"])
    build_id = build_id_path.read_text(encoding="ascii").strip()
    if not BUILD_ID.fullmatch(build_id):
        parser.error(f"invalid GNU build ID in {build_id_path}: {build_id!r}")

    output = pathlib.Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(
        "// Generated by //kernel/phys/generate-elf-interp.py.\n"
        f'.ascii "{build_id}"\n',
        encoding="ascii",
    )

    depfile = pathlib.Path(args.depfile)
    depfile.parent.mkdir(parents=True, exist_ok=True)
    depfile.write_text(
        f"{output}: {metadata_path} {build_id_path}\n", encoding="utf-8"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
