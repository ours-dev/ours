"""Generate physload's module-ABI export table from a first link pass.

physload publishes the symbols a physload_module() binds against.  The names
are C++ mangled, so they cannot be written down in the source that defines
them -- the preprocessor never sees the mangled spelling.  Instead the image
is linked twice: this script reads the symbol table of the first pass and
emits an assembly table of {name, address} rows, which the second pass links
into .phys.exports.  Addresses shift between the passes, but the table names
its targets as symbols, so the second-pass linker resolves them itself.

The export set is every GLOBAL symbol left with default visibility.  That is
an explicit set rather than "everything": the tree force-includes
ours/hidden.hpp, so a symbol only reaches default visibility by carrying
PHYS_EXPORT on its declaration (see ours/phys/exports.hpp).
"""

import argparse
import json
import subprocess
import sys

# Symbols that carry no address a module could bind to.
_NON_ADDRESS_SECTIONS = frozenset({"Undefined", "Absolute", "Common", "Processor Specific"})


def exported_symbols(readelf: str, image: str) -> list[str]:
    output = subprocess.run(
        [readelf, "--elf-output-style=JSON", "--symbols", image],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    files = json.loads(output)

    names: list[str] = []
    seen: set[str] = set()
    for entry in files:
        for wrapper in entry.get("Symbols", []):
            symbol = wrapper["Symbol"]
            if symbol["Binding"]["Name"] != "Global":
                continue
            # An empty flag list is STV_DEFAULT; anything else is hidden,
            # protected or internal, none of which a module may bind to.
            if symbol["Other"]["Flags"]:
                continue
            if symbol["Section"]["Name"] in _NON_ADDRESS_SECTIONS:
                continue
            name = symbol["Name"]["Name"]
            if not name or name in seen:
                continue
            seen.add(name)
            names.append(name)

    names.sort()
    return names


def render(names: list[str]) -> str:
    lines = [
        "// Generated by kernel/phys/gen-phys-exports.py -- do not edit.",
        "//",
        "// physload's module ABI: one {name, address} row per exported symbol,",
        "// collected by phys.ld between __phys_exports_start and",
        "// __phys_exports_end (see ours/phys/exports.hpp).",
        "",
        '\t.section .rodata.phys.exports.str,"aMS",@progbits,1',
    ]
    for index, name in enumerate(names):
        lines.append(f".Lname{index}:")
        lines.append(f'\t.asciz "{name}"')

    lines += [
        "",
        # "aw", not "a": each row's second word is an absolute pointer to
        # the exported symbol, which under -fPIC the linker resolves as an
        # R_X86_64_RELATIVE relocation fixed up at load time.  A relocation
        # target has to be in a writable section for the linker to accept
        # it -- lld refuses outright ("recompile with -fPIC", a symptom
        # rather than the cause) if the section's own flags don't declare
        # SHF_WRITE, regardless of which PHDR physload.ld later assigns it
        # to.
        '\t.section .phys.exports,"aw",@progbits',
        "\t.balign 8",
    ]
    for index, name in enumerate(names):
        lines.append(f"\t.quad .Lname{index}")
        lines.append(f"\t.quad {name}")

    lines += [
        "",
        '\t.section .note.GNU-stack,"",@progbits',
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--readelf", required=True)
    parser.add_argument("--image", required=True)
    parser.add_argument("--output", required=True)
    parser.add_argument("--depfile")
    parsed = parser.parse_args()

    names = exported_symbols(parsed.readelf, parsed.image)
    if not names:
        print(
            f"error: {parsed.image} exports no symbols; a module could not bind "
            "anything against it (is PHYS_EXPORT reaching the declarations?)",
            file=sys.stderr,
        )
        return 1

    with open(parsed.output, "w") as output:
        output.write(render(names))

    if parsed.depfile:
        with open(parsed.depfile, "w") as depfile:
            depfile.write(f"{parsed.output}: {parsed.image}\n")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
